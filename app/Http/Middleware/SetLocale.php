namespace App\Http\Middleware;

use Closure;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\App;
use Illuminate\Support\Facades\View;
use Symfony\Component\HttpFoundation\Response;

class SetLocale
{
    /**
     * Supported languages.
     *
     * @var array<string, array{name: string, native: string}>
     */
    protected array $supportedLanguages = [
        'en' => ['name' => 'English', 'native' => 'English'],
    ];

    /**
     * Handle an incoming request.
     */
    public function handle(Request $request, Closure $next): Response
    {
        // Priority: query param > authenticated user > cookie > default
        $lang = $request->query('lang');

        if ($lang && isset($this->supportedLanguages[$lang])) {
            App::setLocale($lang);
            cookie()->queue('pivlu_locale', $lang, 525600); // 1 year
        } elseif ($request->user() && isset($this->supportedLanguages[$request->user()->locale])) {
            $lang = $request->user()->locale;
            App::setLocale($lang);
        } elseif ($cookie = $request->cookie('pivlu_locale')) {
            if (isset($this->supportedLanguages[$cookie])) {
                $lang = $cookie;
                App::setLocale($lang);
            }
        }

        $lang = $lang ?? App::getLocale();

        View::share('lang', $lang);
        View::share('supportedLanguages', $this->supportedLanguages);

        return $next($request);
    }
}
